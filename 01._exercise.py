"""
We have a variable named distance_km below with the value 4135 - 
indicating the straight-line distance between San Francisco and New York in Kilometers. 
Create another variable called distance_mi and store the distance value in miles.
"""

distance_km = 4135;
distance_mi = distance_km / 1.60934
print("The distance from San Francisco and New York is ",distance_mi, "miles")